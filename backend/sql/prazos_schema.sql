create or replace function public.prazos_apply_dataset(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, prazos
as $$
declare
  v_batch_id uuid;
  v_valid_from date;
  v_valid_to date;
  v_validity_type text;
  v_source_type text;
  v_route_payload jsonb;
  v_route_version_id uuid;
  v_route_identity_key text;
  v_route_count integer := 0;
  v_row_count integer := 0;
begin
  if p_payload is null then
    raise exception 'Payload de persistencia nao enviado.';
  end if;

  v_valid_from := (p_payload ->> 'valid_from')::date;
  v_valid_to := nullif(p_payload ->> 'valid_to', '')::date;
  v_validity_type := upper(coalesce(p_payload ->> 'validity_type', ''));
  v_source_type := upper(coalesce(p_payload ->> 'source_type', ''));

  if v_validity_type not in ('PADRAO', 'PONTUAL') then
    raise exception 'Tipo de vigencia invalido: %', v_validity_type;
  end if;

  if v_source_type not in ('CALCULO_MANUAL', 'PLANILHA_LOGISTICA', 'PLANILHA_VALIDADA') then
    raise exception 'Tipo de origem invalido: %', v_source_type;
  end if;

  if v_valid_from is null then
    raise exception 'Data inicial de vigencia obrigatoria.';
  end if;

  if v_validity_type = 'PONTUAL' and v_valid_to is null then
    raise exception 'Para vigencia pontual, informe a data final.';
  end if;

  if v_valid_to is not null and v_valid_to < v_valid_from then
    raise exception 'A data final nao pode ser anterior a data inicial.';
  end if;

  insert into prazos.import_batches (
    source_type,
    source_name,
    file_name,
    validity_type,
    valid_from,
    valid_to,
    observation,
    payload,
    planning_batch_id
  )
  values (
    v_source_type,
    nullif(p_payload ->> 'source_name', ''),
    nullif(p_payload ->> 'file_name', ''),
    v_validity_type,
    v_valid_from,
    v_valid_to,
    nullif(p_payload ->> 'observation', ''),
    p_payload -> 'payload',
    nullif(p_payload ->> 'planning_batch_id', '')::uuid
  )
  returning id into v_batch_id;

  for v_route_payload in
    select value
    from jsonb_array_elements(coalesce(p_payload -> 'route_versions', '[]'::jsonb))
  loop
    v_route_identity_key := coalesce(v_route_payload ->> 'route_identity_key', '');

    if v_route_identity_key = '' then
      raise exception 'Rota sem chave de identidade enviada para persistencia.';
    end if;

    if v_validity_type = 'PADRAO' then
      if exists (
        select 1
        from prazos.route_versions existing_version
        where existing_version.route_identity_key = v_route_identity_key
          and existing_version.validity_type = 'PADRAO'
          and existing_version.valid_from > v_valid_from
          and coalesce(existing_version.valid_to, date '9999-12-31') >= v_valid_from
      ) then
        raise exception 'Ja existe um prazo PADRAO futuro ou sobreposto para a rota % a partir de %.', v_route_identity_key, v_valid_from;
      end if;

      update prazos.route_versions
      set
        valid_to = case when valid_from = v_valid_from then v_valid_from else v_valid_from - 1 end,
        status = 'ENCERRADO',
        closed_at = timezone('utc', now()),
        closed_by_batch_id = v_batch_id
      where route_identity_key = v_route_identity_key
        and validity_type = 'PADRAO'
        and (
          (valid_from < v_valid_from and coalesce(valid_to, date '9999-12-31') >= v_valid_from)
          or valid_from = v_valid_from
        );
    else
      if exists (
        select 1
        from prazos.route_versions existing_version
        where existing_version.route_identity_key = v_route_identity_key
          and existing_version.validity_type = 'PONTUAL'
          and daterange(existing_version.valid_from, coalesce(existing_version.valid_to, existing_version.valid_from), '[]')
              && daterange(v_valid_from, coalesce(v_valid_to, v_valid_from), '[]')
      ) then
        raise exception 'Ja existe uma vigencia PONTUAL sobreposta para a rota % no periodo informado.', v_route_identity_key;
      end if;
    end if;

    insert into prazos.route_versions (
      batch_id,
      route_identity_key,
      source_type,
      validity_type,
      valid_from,
      valid_to,
      observation,
      cd,
      modal,
      geography,
      commercial_location,
      locality,
      planning_route_version_id
    )
    values (
      v_batch_id,
      v_route_identity_key,
      v_source_type,
      v_validity_type,
      v_valid_from,
      v_valid_to,
      nullif(p_payload ->> 'observation', ''),
      coalesce(v_route_payload ->> 'cd', ''),
      coalesce(v_route_payload ->> 'modal', ''),
      coalesce(v_route_payload ->> 'geography', ''),
      coalesce(v_route_payload ->> 'commercial_location', ''),
      nullif(v_route_payload ->> 'locality', ''),
      nullif(v_route_payload ->> 'planning_route_version_id', '')::uuid
    )
    returning id into v_route_version_id;

    insert into prazos.route_logic_events (
      route_version_id,
      event_order,
      route_destination,
      event_day,
      cutoff_hour,
      delivery_day,
      frequency,
      raw_event
    )
    select
      v_route_version_id,
      coalesce((logic_event ->> 'event_order')::integer, logic_index::integer),
      nullif(logic_event ->> 'route_destination', ''),
      coalesce(logic_event ->> 'event_day', ''),
      coalesce((logic_event ->> 'cutoff_hour')::integer, 0),
      coalesce(logic_event ->> 'delivery_day', ''),
      coalesce(logic_event ->> 'frequency', 'SEMANAL'),
      logic_event -> 'raw_event'
    from jsonb_array_elements(coalesce(v_route_payload -> 'logic_events', '[]'::jsonb))
      with ordinality as logic_events(logic_event, logic_index);

    insert into prazos.deadline_rows (
      route_version_id,
      route_identity_key,
      cd,
      modal,
      geography,
      commercial_location,
      locality,
      metodo_cd,
      prazo_cd,
      metodo_tr,
      prazo_tr,
      prazo_cliente,
      horario_inicial,
      horario_final,
      rota_fixa,
      segunda,
      terca,
      quarta,
      quinta,
      sexta,
      sabado,
      domingo,
      raw_row
    )
    select
      v_route_version_id,
      v_route_identity_key,
      coalesce(deadline_row ->> 'cd', ''),
      coalesce(deadline_row ->> 'modal', ''),
      coalesce(deadline_row ->> 'geography', ''),
      coalesce(deadline_row ->> 'commercial_location', ''),
      nullif(deadline_row ->> 'locality', ''),
      coalesce(deadline_row ->> 'metodo_cd', 'SUBSTITUIR'),
      coalesce((deadline_row ->> 'prazo_cd')::integer, 0),
      coalesce(deadline_row ->> 'metodo_tr', 'SUBSTITUIR'),
      coalesce((deadline_row ->> 'prazo_tr')::integer, 0),
      coalesce((deadline_row ->> 'prazo_cliente')::integer, 0),
      coalesce((deadline_row ->> 'horario_inicial')::integer, 0),
      coalesce((deadline_row ->> 'horario_final')::integer, 0),
      coalesce(deadline_row ->> 'rota_fixa', 'NAO'),
      coalesce((deadline_row ->> 'segunda')::boolean, false),
      coalesce((deadline_row ->> 'terca')::boolean, false),
      coalesce((deadline_row ->> 'quarta')::boolean, false),
      coalesce((deadline_row ->> 'quinta')::boolean, false),
      coalesce((deadline_row ->> 'sexta')::boolean, false),
      coalesce((deadline_row ->> 'sabado')::boolean, false),
      coalesce((deadline_row ->> 'domingo')::boolean, false),
      deadline_row -> 'raw_row'
    from jsonb_array_elements(coalesce(v_route_payload -> 'rows', '[]'::jsonb)) as deadline_rows(deadline_row);

    v_route_count := v_route_count + 1;
    v_row_count := v_row_count + coalesce(jsonb_array_length(v_route_payload -> 'rows'), 0);
  end loop;

  return jsonb_build_object(
    'batch_id', v_batch_id,
    'route_versions', v_route_count,
    'deadline_rows', v_row_count,
    'validity_type', v_validity_type,
    'valid_from', v_valid_from,
    'valid_to', v_valid_to
  );
end;
$$;

